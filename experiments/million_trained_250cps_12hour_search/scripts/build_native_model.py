"""Generate native search data directly from the authoritative Python catalog."""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[3];sys.path.insert(0,str(ROOT/'src'))
from ccsr.game.gamestate import Gamestate
s=Gamestate('2.031');names=[n for n,b in s.building_catalog.items() if b.base_price<1_000_000]
upgrades=[(n,u) for n,u in s.upgrade_catalog.items() if u.price<1_000_000]
lines=['// Generated by build_native_model.py; do not hand-edit.','#pragma once','#include <cstdint>',
       f'constexpr int NB={len(names)}, NU={len(upgrades)}, NP=100;',
       'constexpr double BASE_CPS[NB]={'+','.join(repr(s.building_catalog[n].base_cps) for n in names)+'};',
       'constexpr std::uint64_t PRICES[NB][NP]={']
for n in names:lines.append('{'+','.join(str(s.building_price(n,i))+'ULL' for i in range(100))+'},')
lines+=['};','struct UpgradeData {std::uint64_t price;int req[NB];int building;double cursor,finger,production,mouse;int synergy;double cookies,handmade;};','constexpr UpgradeData UPGRADES[NU]={']
for n,u in upgrades:
    req=dict(u.requirements)
    lines.append('{'+str(u.price)+'ULL,{'+','.join(str(req.get(b,0)) for b in names)+'},'+','.join(map(str,[names.index(u.building) if u.building else -1,u.cursor_multiplier,u.finger_add,u.production_multiplier,u.mouse_cps_fraction,names.index(u.grandma_synergy) if u.grandma_synergy else -1,u.cookies_required,u.handmade_required]))+'}, // '+n)
lines+=['};']
model_path=Path(__file__).with_name('native_model_data.hpp')
model_pending=model_path.with_suffix('.hpp.pending');model_pending.write_text('\n'.join(lines)+'\n');model_pending.replace(model_path)
import json
names_path=Path(__file__).with_name('native_names.json')
names_pending=names_path.with_suffix('.json.pending');names_pending.write_text(json.dumps(dict(buildings=names,upgrades=[n for n,u in upgrades]),indent=2)+'\n');names_pending.replace(names_path)
